-- Neon schema for homepage data (without Supabase auth dependencies)

CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  nombre TEXT NOT NULL,
  precio NUMERIC NOT NULL CHECK (precio > 0),
  categoria TEXT NOT NULL,
  imagen TEXT NOT NULL,
  popular BOOLEAN DEFAULT FALSE,
  stock INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.orders (
  id UUID PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  user_id TEXT,
  status TEXT DEFAULT 'Pendiente'
);

CREATE TABLE IF NOT EXISTS public.hero_slides (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  subtitle TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  cta_text TEXT DEFAULT 'Ver Catalogo',
  cta_link TEXT DEFAULT '/catalogo',
  image_url TEXT NOT NULL,
  "order" INTEGER DEFAULT 0,
  active BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.promotions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  image_url TEXT NOT NULL,
  original_price NUMERIC NOT NULL CHECK (original_price > 0),
  sale_price NUMERIC NOT NULL CHECK (sale_price > 0),
  discount_percent INTEGER GENERATED ALWAYS AS (
    ROUND(((original_price - sale_price) / original_price * 100))::INTEGER
  ) STORED,
  cta_link TEXT DEFAULT '/catalogo',
  active BOOLEAN DEFAULT TRUE,
  expires_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.testimonials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  name TEXT NOT NULL,
  role TEXT DEFAULT 'Cliente',
  avatar_url TEXT,
  text TEXT NOT NULL,
  rating INTEGER DEFAULT 5 CHECK (rating >= 1 AND rating <= 5),
  active BOOLEAN DEFAULT TRUE
);

CREATE OR REPLACE VIEW public.homepage_stats AS
SELECT
  (SELECT COALESCE(COUNT(*), 0) FROM public.orders WHERE status IN ('Recibido', 'Preparando', 'En Camino', 'Entregado')) AS total_orders,
  (SELECT COALESCE(COUNT(DISTINCT user_id), 0) FROM public.orders WHERE status IN ('Recibido', 'Preparando', 'En Camino', 'Entregado')) AS total_customers,
  (SELECT COALESCE(COUNT(*), 0) FROM public.products WHERE stock > 0) AS total_products;

