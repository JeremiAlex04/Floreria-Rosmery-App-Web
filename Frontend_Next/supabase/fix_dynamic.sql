-- ================================================
-- TABLAS PARA HOME DINÁMICO (Versión Corregida)
-- ================================================

-- 1. Beneficios
CREATE TABLE IF NOT EXISTS public.benefits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  icon TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  "order" INTEGER DEFAULT 0,
  active BOOLEAN DEFAULT TRUE
);

-- 2. Categorías
CREATE TABLE IF NOT EXISTS public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  title TEXT NOT NULL,
  slug TEXT NOT NULL,
  image_url TEXT NOT NULL,
  "order" INTEGER DEFAULT 0,
  active BOOLEAN DEFAULT TRUE
);

-- 3. Pasos de Compra
CREATE TABLE IF NOT EXISTS public.buying_steps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  icon TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  color_class TEXT DEFAULT 'bg-pink-400',
  "order" INTEGER DEFAULT 0,
  active BOOLEAN DEFAULT TRUE
);

-- 4. Galería de Instagram
CREATE TABLE IF NOT EXISTS public.gallery_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  image_url TEXT NOT NULL,
  alt_text TEXT,
  "order" INTEGER DEFAULT 0,
  active BOOLEAN DEFAULT TRUE
);

-- 5. Configuración de la Empresa
CREATE TABLE IF NOT EXISTS public.company_settings (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  phone TEXT DEFAULT '(01) 245-8365',
  whatsapp TEXT DEFAULT '+51 912 053 432',
  email TEXT DEFAULT 'contacto@floreriarosmery.com',
  address TEXT DEFAULT 'Av. Las Flores 123, Lima', 
  schedule_mon_sat TEXT DEFAULT '9:00 AM - 7:00 PM',
  instagram_url TEXT DEFAULT 'https://instagram.com',
  facebook_url TEXT,
  tiktok_url TEXT,
  map_iframe_url TEXT
);

-- Habilitar RLS
ALTER TABLE public.benefits ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.buying_steps ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gallery_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.company_settings ENABLE ROW LEVEL SECURITY;

-- Policies (Lectura pública, Escritura Admin)
CREATE POLICY "Public read benefits" ON public.benefits FOR SELECT USING (true);
CREATE POLICY "Admin manage benefits" ON public.benefits FOR ALL USING (public.is_admin());

CREATE POLICY "Public read categories" ON public.categories FOR SELECT USING (true);
CREATE POLICY "Admin manage categories" ON public.categories FOR ALL USING (public.is_admin());

CREATE POLICY "Public read steps" ON public.buying_steps FOR SELECT USING (true);
CREATE POLICY "Admin manage steps" ON public.buying_steps FOR ALL USING (public.is_admin());

CREATE POLICY "Public read gallery" ON public.gallery_images FOR SELECT USING (true);
CREATE POLICY "Admin manage gallery" ON public.gallery_images FOR ALL USING (public.is_admin());

CREATE POLICY "Public read settings" ON public.company_settings FOR SELECT USING (true);
CREATE POLICY "Admin manage settings" ON public.company_settings FOR ALL USING (public.is_admin());

