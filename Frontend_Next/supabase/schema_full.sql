-- --------------------------------------------------------
-- 1. USUARIOS Y PERFILES (AUTH)
-- --------------------------------------------------------

-- Tabla de Perfiles (Extiende auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID REFERENCES auth.users(id) PRIMARY KEY,
  full_name TEXT,
  role TEXT DEFAULT 'customer' CHECK (role IN ('admin', 'customer')),
  phone TEXT,
  avatar_url TEXT,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- RLS: Seguridad para Perfiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
    CREATE POLICY "Usuarios ven su propio perfil" ON public.profiles FOR SELECT USING (auth.uid() = id);
    CREATE POLICY "Usuarios actualizan su propio perfil" ON public.profiles FOR UPDATE USING (auth.uid() = id);
    CREATE POLICY "Admin ve todos los perfiles" ON public.profiles FOR ALL USING (public.is_admin());
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- Función: Crear perfil automáticamente al registrarse
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, role)
  VALUES (new.id, new.raw_user_meta_data->>'full_name', 'customer');
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger: Ejecutar función al crear usuario
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- Función Helper: Verificar si es admin
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- --------------------------------------------------------
-- 2. TIENDA Y PRODUCTOS
-- --------------------------------------------------------

-- Tabla de Productos
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  nombre TEXT NOT NULL UNIQUE,
  precio NUMERIC NOT NULL,
  categoria TEXT NOT NULL,
  imagen TEXT NOT NULL,
  description TEXT,
  stock INTEGER DEFAULT 0,
  popular BOOLEAN DEFAULT FALSE,
  active BOOLEAN DEFAULT TRUE
);

-- RLS Productos
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
    CREATE POLICY "Public read products" ON public.products FOR SELECT USING (active = true);
    CREATE POLICY "Admin manage products" ON public.products FOR ALL USING (public.is_admin());
EXCEPTION WHEN duplicate_object THEN NULL; END $$;


-- --------------------------------------------------------
-- 3. PEDIDOS (ORDERS)
-- --------------------------------------------------------

-- Tabla Pedidos
CREATE TABLE IF NOT EXISTS public.orders (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  user_id UUID REFERENCES auth.users(id),
  total NUMERIC NOT NULL,
  status TEXT DEFAULT 'Pendiente' CHECK (status IN ('Pendiente', 'Recibido', 'Preparando', 'En Camino', 'Entregado', 'Cancelado')),
  payment_method TEXT,
  voucher_url TEXT,
  shipping_address JSONB,
  contact_info JSONB
);

-- Tabla Items del Pedido
CREATE TABLE IF NOT EXISTS public.order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  order_id UUID REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES public.products(id),
  quantity INTEGER NOT NULL,
  price_at_purchase NUMERIC NOT NULL
);

-- RLS Pedidos
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
    CREATE POLICY "Users read own orders" ON public.orders FOR SELECT USING (auth.uid() = user_id);
    CREATE POLICY "Users create own orders" ON public.orders FOR INSERT WITH CHECK (auth.uid() = user_id);
    CREATE POLICY "Admin manage all orders" ON public.orders FOR ALL USING (public.is_admin());
    
    CREATE POLICY "Users read own items" ON public.order_items FOR SELECT USING (
        EXISTS (SELECT 1 FROM public.orders WHERE id = order_items.order_id AND user_id = auth.uid())
    );
    CREATE POLICY "Users create own items" ON public.order_items FOR INSERT WITH CHECK (
        EXISTS (SELECT 1 FROM public.orders WHERE id = order_items.order_id AND user_id = auth.uid())
    );
    CREATE POLICY "Admin manage all items" ON public.order_items FOR ALL USING (public.is_admin());
EXCEPTION WHEN duplicate_object THEN NULL; END $$;


