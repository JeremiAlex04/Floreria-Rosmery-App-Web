-- 6. Auditoría y Registro de Acciones
CREATE TABLE IF NOT EXISTS public.audit_logs (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  user_id UUID REFERENCES auth.users(id),
  action TEXT NOT NULL, -- e.g., 'INSERT', 'UPDATE', 'DELETE'
  table_name TEXT NOT NULL,
  record_id TEXT,
  old_values JSONB,
  new_values JSONB
);

-- Función para descuento automático de stock
CREATE OR REPLACE FUNCTION public.reduce_stock_on_order_received()
RETURNS TRIGGER AS $$
DECLARE
  item RECORD;
BEGIN
  -- Solo actuar si el estado cambia a 'Recibido'
  IF (NEW.status = 'Recibido' AND (OLD.status IS NULL OR OLD.status <> 'Recibido')) THEN
    -- Validar stock para cada item antes de descontar
    FOR item IN 
      SELECT p.id, p.nombre, p.stock, oi.quantity 
      FROM public.order_items oi 
      JOIN public.products p ON p.id = oi.product_id 
      WHERE oi.order_id = NEW.id 
    LOOP
      IF item.stock < item.quantity THEN
        RAISE EXCEPTION 'Stock insuficiente para el producto "%": disponible %, solicitado %', 
          item.nombre, item.stock, item.quantity;
      END IF;

      UPDATE public.products 
      SET stock = stock - item.quantity 
      WHERE id = item.id;
    END LOOP;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER tr_reduce_stock_on_order_received
  AFTER UPDATE ON public.orders
  FOR EACH ROW EXECUTE PROCEDURE public.reduce_stock_on_order_received();

-- Función para registrar auditoría automáticamente
CREATE OR REPLACE FUNCTION public.log_admin_action()
RETURNS TRIGGER AS $$
DECLARE
    v_user_id UUID := auth.uid();
BEGIN
    INSERT INTO public.audit_logs (user_id, action, table_name, record_id, old_values, new_values)
    VALUES (
        v_user_id,
        TG_OP,
        TG_TABLE_NAME,
        CASE 
            WHEN TG_OP = 'DELETE' THEN OLD.id::TEXT 
            ELSE NEW.id::TEXT 
        END,
        CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) ELSE NULL END,
        CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) ELSE NULL END
    );
    RETURN NULL; -- result is ignored since this is an AFTER trigger
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Aplicar auditoría a Tablas Críticas
CREATE TRIGGER tr_audit_products
  AFTER INSERT OR UPDATE OR DELETE ON public.products
  FOR EACH ROW EXECUTE PROCEDURE public.log_admin_action();

CREATE TRIGGER tr_audit_orders
  AFTER INSERT OR UPDATE OR DELETE ON public.orders
  FOR EACH ROW EXECUTE PROCEDURE public.log_admin_action();

