-- 1. Tabla de Perfiles para Roles
CREATE TABLE public.profiles (
  id UUID REFERENCES auth.users(id) PRIMARY KEY,
  full_name TEXT,
  role TEXT DEFAULT 'customer' CHECK (role IN ('admin', 'customer')),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Trigger para crear perfil automáticamente al registrarse
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, role)
  VALUES (new.id, new.raw_user_meta_data->>'full_name', 'customer');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- 2. Función para verificar si un usuario es Admin
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
BEGIN
  RETURN (
    SELECT role = 'admin' 
    FROM public.profiles 
    WHERE id = auth.uid()
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Tipos de productos (categorías)
CREATE TYPE product_category AS ENUM (
  'Aniversario', 'Arreglos en Caja', 'Bodas', 'Centros de Mesa', 'Condolencias', 
  'Cumpleaños', 'Día del Padre', 'Día de la Madre', 'Girasoles', 'Graduaciones', 
  'Orquídeas', 'Ramos de Mano', 'Ramos Premium', 'Rosas', 'San Valentín', 'Tulipanes'
);

-- Estado del pedido
CREATE TYPE order_status AS ENUM (
  'Recibido', 'Preparando', 'En Camino', 'Entregado', 'Cancelado'
);

-- 3. Tabla de Productos con Integridad
CREATE TABLE public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  nombre TEXT NOT NULL UNIQUE, -- Evita duplicados por nombre
  precio NUMERIC NOT NULL CHECK (precio > 0), -- Precio positivo
  categoria TEXT NOT NULL,
  ocasion TEXT[] DEFAULT '{}',
  imagen TEXT NOT NULL,
  popular BOOLEAN DEFAULT FALSE,
  stock INTEGER DEFAULT 100 CHECK (stock >= 0), -- Stock no negativo
  descripcion TEXT
);

-- 4. Tabla de Pedidos e Items
CREATE TABLE public.orders (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  status order_status DEFAULT 'Recibido',
  total NUMERIC NOT NULL CHECK (total >= 0),
  shipping_address JSONB,
  contact_info JSONB
);

CREATE TABLE public.order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id UUID REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  price_at_purchase NUMERIC NOT NULL CHECK (price_at_purchase >= 0)
);

-- 5. Políticas de Seguridad (RLS) Refinadas

-- Productos
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Lectura pública de productos" ON public.products FOR SELECT USING (true);
CREATE POLICY "Solo admin gestiona productos" ON public.products 
  FOR ALL USING (public.is_admin());

-- Pedidos
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Usuarios ven sus propios pedidos" ON public.orders 
  FOR SELECT USING (auth.uid() = user_id OR public.is_admin());
CREATE POLICY "Usuarios crean sus propios pedidos" ON public.orders 
  FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Solo admin gestiona todos los pedidos" ON public.orders 
  FOR UPDATE USING (public.is_admin());

-- Items (Heredan de pedidos)
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Ver items propios o admin" ON public.order_items FOR SELECT USING (
  EXISTS (SELECT 1 FROM public.orders WHERE id = order_id AND (user_id = auth.uid() OR public.is_admin()))
);
CREATE POLICY "Inserción de items ligada al usuario" ON public.order_items FOR INSERT WITH CHECK (
  EXISTS (SELECT 1 FROM public.orders WHERE id = order_id AND user_id = auth.uid())
);
