-- Tipos de productos (categorías)
CREATE TYPE product_category AS ENUM (
  'Aniversario', 'Arreglos en Caja', 'Bodas', 'Centros de Mesa', 'Condolencias', 
  'Cumpleaños', 'Día del Padre', 'Día de la Madre', 'Girasoles', 'Graduaciones', 
  'Orquídeas', 'Ramos de Mano', 'Ramos Premium', 'Rosas', 'San Valentín', 'Tulipanes'
);

-- Estado del pedido
CREATE TYPE order_status AS ENUM (
  'Recibido', 'Preparando', 'En Camino', 'Entregado', 'Cancelado'
);

-- Tabla de Productos
CREATE TABLE public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  nombre TEXT NOT NULL,
  precio NUMERIC NOT NULL,
  categoria TEXT NOT NULL, -- Usamos TEXT para flexibilidad o product_category si quieres estricto
  ocasion TEXT[] DEFAULT '{}',
  imagen TEXT NOT NULL,
  popular BOOLEAN DEFAULT FALSE,
  stock INTEGER DEFAULT 100,
  descripcion TEXT
);

-- Tabla de Pedidos
CREATE TABLE public.orders (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  user_id UUID REFERENCES auth.users(id), -- Vincula con el usuario de Supabase
  status order_status DEFAULT 'Recibido',
  total NUMERIC NOT NULL,
  shipping_address JSONB, -- Dirección de envío
  contact_info JSONB -- Teléfono, etc.
);

-- Tabla de Items del Pedido
CREATE TABLE public.order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id UUID REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES public.products(id),
  quantity INTEGER NOT NULL,
  price_at_purchase NUMERIC NOT NULL -- Precio al momento de la compra
);

-- Políticas de Seguridad (RLS)

-- Productos: Todos pueden ver, solo admin puede editar (por ahora permitimos todo para facilitar desarrollo, luego restringir)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Ver productos para todos" ON public.products
  FOR SELECT USING (true);

CREATE POLICY "Admin insertar productos" ON public.products
  FOR INSERT WITH CHECK (auth.role() = 'authenticated'); -- Ajustar cuando implementemos roles

CREATE POLICY "Admin actualizar productos" ON public.products
  FOR UPDATE USING (auth.role() = 'authenticated');

-- Pedidos: El usuario solo ve sus propios pedidos
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Ver mis pedidos" ON public.orders
  FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Crear pedido" ON public.orders
  FOR INSERT WITH CHECK (auth.uid() = user_id);

-- Items: Ver items de mis pedidos
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Ver mis items" ON public.order_items
  FOR SELECT USING (
    EXISTS (
      SELECT 1 FROM public.orders
      WHERE orders.id = order_items.order_id
      AND orders.user_id = auth.uid()
    )
  );

CREATE POLICY "Crear items" ON public.order_items
  FOR INSERT WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.orders
      WHERE orders.id = order_items.order_id
      AND orders.user_id = auth.uid()
    )
  );
