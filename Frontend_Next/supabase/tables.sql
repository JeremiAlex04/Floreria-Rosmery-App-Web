SELECT
  (SELECT COALESCE(COUNT(*), 0) FROM public.orders WHERE status IN ('Recibido', 'Preparando', 'En Camino', 'Entregado')) AS total_orders,
  (SELECT COALESCE(COUNT(DISTINCT user_id), 0) FROM public.orders WHERE status IN ('Recibido', 'Preparando', 'En Camino', 'Entregado')) AS total_customers,
  (SELECT COALESCE(COUNT(*), 0) FROM public.products WHERE stock > 0) AS total_products;

